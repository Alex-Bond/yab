// Shared by the native WebKit suite and the live agent-tab check. The
// production runtime is loaded separately, never copied into this fixture.
(async () => {
  const E=window.__yabEditor, checks=[], errors=[];
  const check=(name,ok,detail)=>{checks.push({name,passed:!!ok,detail});if(!ok)errors.push(name)};
  const wait=ms=>new Promise(r=>setTimeout(r,ms));
  const $=id=>document.getElementById(id), css=e=>getComputedStyle(e);
  const defaults={enabled:true,hue:205,amount:0,mode:'',font:0,size:1,spacing:1,photos:1,css:'',hidden:[]};
  const base=()=>({...defaults,hidden:[]});
  const colors=[$('inherit'),$('inline')].map(e=>css(e).color);
  const originalFilter=css($('photo')).filter;
  const originalFont=css($('inherit')).fontSize;
  let look=base(); E.apply(look);
  check('unchanged settings preserve the page',css($('inherit')).color===colors[0]&&css($('inherit')).fontSize===originalFont);
  look={...look,size:1.2,spacing:1.1};E.apply(look);
  check('inherited font scales once',Math.abs(parseFloat(css($('inherit')).fontSize)-24)<.05,css($('inherit')).fontSize);
  look={...look,size:1.4};E.apply(look);
  check('drag applies in the same turn',Math.abs(parseFloat(css($('inherit')).fontSize)-28)<.05);
  look={...look,hue:160,amount:.8};E.apply(look);
  check('color changes text',css($('inherit')).color!==colors[0]);
  check('color preserves photographs',css($('photo')).filter===originalFilter);
  look={...look,mode:'dark'};E.apply(look,'scheme');await wait(340);
  check('dark mode gives dark paper',(()=>{const rgb=css(document.documentElement).backgroundColor.match(/[\d.]+/g).map(Number);return Math.max(...rgb.slice(0,3))<90})(),css(document.documentElement).backgroundColor);
  check('scheme keeps photo filter',css($('photo')).filter===originalFilter);
  look={...look,photos:.3};E.apply(look);
  check('photo control keeps site filter',css($('photo')).filter.includes('contrast(1.1)')&&css($('photo')).filter.includes('saturate(0.3)'));
  const sibling=E.similar('#second');
  check('similar elements found',sibling.length===3,sibling);
  check('similar selectors resolve to distinct nodes',new Set(sibling.map(s=>document.querySelector(s.selector))).size===3);
  check('similar rectangles have dimensions',sibling.every(s=>s.rect.length===4&&s.rect[2]>0&&s.rect[3]>0));
  // Flow positions exclude the presentation offset of an unfinished FLIP.
  // Frame-by-frame presentation acceptance belongs to the native QA card.
  const top=$('third').offsetTop;
  look={...look,hidden:[{selector:'#second',label:'Second story'}]};E.apply(look,'hide');await wait(240);
  check('hide removes the element from flow',css($('second')).display==='none');
  check('gap closes behind hidden block',$('third').offsetTop<top);
  const closedTop=$('third').offsetTop;
  E.apply(look,'peek',true);
  check('Original does not reflow neighbors',$('third').offsetTop===closedTop);
  check('Original shows a fixed copy',document.querySelectorAll('[data-yab-editor-overlay]').length===1);
  E.apply(look,'peek',false);await wait(250);
  check('releasing Original removes the copy',document.querySelectorAll('[data-yab-editor-overlay]').length===0);
  check('releasing Original keeps layout',$('third').offsetTop===closedTop);
  look={...look,hidden:[]};E.apply(look,'restore');await wait(240);
  check('Show restores flow',css($('second')).display!=='none'&&$('third').offsetTop===top);
  look={...base(),css:'#inline { padding-left: 23px; }'};E.apply(look);
  check('custom CSS applies',css($('inline')).paddingLeft==='23px');
  look={...look,css:''};E.apply(look);
  check('deleting CSS removes its effect',css($('inline')).paddingLeft==='0px');
  look={...base(),size:1.25,amount:.7};E.apply(look);
  const added=document.createElement('span');added.id='dynamic';added.textContent='Added by SPA';$('stories').append(added);
  await wait(60);
  check('SPA text scales once',Math.abs(parseFloat(css(added).fontSize)-25)<.05,css(added).fontSize);
  check('SPA text wears current palette',css(added).color!==colors[0]);
  E.apply({...look,enabled:false},'toggle');await wait(250);
  check('off restores font',css($('inherit')).fontSize===originalFont);
  check('off restores original inline priority',$('inline').style.getPropertyValue('color')==='rgb(80, 30, 20)'&&$('inline').style.getPropertyPriority('color')==='important');
  check('off restores photos',css($('photo')).filter===originalFilter);
  E.apply({...look,hue:330,amount:1},'glide');await wait(40);
  E.apply({...base(),hue:45,amount:.2},'direct');
  const immediate=css($('inherit')).color;await wait(600);
  check('new input cancels an unfinished spring',css($('inherit')).color===immediate);
  E.apply({...look,font:2},'font');E.apply({...base(),font:3},'direct');await wait(200);
  check('an interrupted font dip cannot install stale font',css($('inherit')).fontFamily.toLowerCase().includes('charter'),css($('inherit')).fontFamily);
  E.apply({...look,hidden:[{selector:'[',label:'Bad selector'}]});
  check('bad saved selector does not stop applying',true);
  E.apply({...base(),mode:'dark',amount:.7,hidden:[{selector:'#second',label:'Second story'}]});
  E.apply({...base(),hidden:[{selector:'#second',label:'Second story'}]},'reset');
  check('Reset starts one shared spring',E.report().spring);
  E.apply(base(),'restore');
  check('staggered Show preserves the Reset spring',E.report().spring);
  E.apply(base());
  check('Reset returns to original colors',css($('inherit')).color===colors[0]);
  check('Reset returns original inline color',css($('inline')).color===colors[1]);
  check('Reset removes all hidden copies',document.querySelectorAll('[data-yab-editor-overlay]').length===0);
  look={...base(),hidden:[{selector:'#second',label:'Second story'}]};E.apply(look);
  const replaced=$('second'), replacement=document.createElement(replaced.tagName);
  replacement.id='second';replacement.className=replaced.className;replacement.textContent='SPA replacement';
  replaced.replaceWith(replacement);await wait(100);
  check('saved hide follows a replaced SPA node',css(replacement).display==='none');
  E.apply(look,'peek',true);
  check('Original can preview a replaced hidden node',document.querySelectorAll('[data-yab-editor-overlay]').length===1);
  E.apply(base(),'restore');await wait(250);
  check('Show restores the replacement instead of the detached node',css(replacement).display!=='none');
  replacement.replaceWith(replaced);E.apply(base());
  added.remove();
  return {passed:errors.length===0,checks:checks.length,results:checks,errors};
})()
